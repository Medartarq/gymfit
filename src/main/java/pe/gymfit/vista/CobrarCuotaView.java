    public int getIdCuota() {
        return Integer.parseInt(txtIdCuota.getText().trim());

    }

    public BigDecimal getMonto() {
        return new BigDecimal(txtMonto.getText().trim());
    }

    public MedioPago getMedio() {
        return MedioPago.valueOf(
                (String) cboMedio.getSelectedItem()
        );
    }

    public void mostrarUsuario(String texto) {
        lblUsuario.setText("Usuario: " + texto);
    }

    public void mostrarExito(String mensaje) {
        lblMensaje.setForeground(VERDE);
        lblMensaje.setText(mensaje);
    }

    public void mostrarError(String mensaje) {
        lblMensaje.setForeground(ROJO);
        lblMensaje.setText("✗ " + mensaje);
    }

    public void limpiar() {
        txtIdCuota.setText("");
        txtMonto.setText("");
        cboMedio.setSelectedIndex(0);
    }

